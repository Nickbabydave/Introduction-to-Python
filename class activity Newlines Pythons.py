#Prompt the user to enter the number of days
days = int(input("Enter number of days:"))
#Calculate hours, minutes, and seconds
hours = days * 24
minutes = hours * 60
seconds = minutes * 60
#Display the results
print("\nEquivalent times:")
print(f"Hours: {hours}")
print(f"Minutes: {minutes}")
print(f"Seconds: {seconds}")



